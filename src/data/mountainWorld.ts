const CHAR_TO_TILE: Record<string, TileType> = {
  '.': 'snow',
  ',': 'path',
  T: 'tree',
  R: 'rock',
  I: 'ice',
  '~': 'chasm',
  '=': 'bridge',
  '^': 'cliff',
};

function parseTileGrid(rows: string[]): TileType[][] {
  return rows.map((row) =>
    row.split('').map((ch) => CHAR_TO_TILE[ch] ?? 'snow')
  );
}

export function isTileSolid(tile: TileType): boolean {
  return (
    tile === 'tree' ||
    tile === 'rock' ||
    tile === 'chasm' ||
    tile === 'cliff'
  );
}

