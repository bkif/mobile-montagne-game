const CHAR_TO_TILE: Record<string, TileType> = {
  G: 'grass',
  '.': 'snow',
  ',': 'path',
  S: 'stone',
  I: 'ice',
  '=': 'bridge',
  T: 'tree',
  R: 'rock',
  '^': 'cliff',
  '~': 'chasm',
  H: 'cabin',
  M: 'mist',
};

function parseGrid(rows: string[]): TileType[][] {
  return rows.map((row) =>
    row.split('').map((ch) => CHAR_TO_TILE[ch] ?? 'snow')
  );
}

export function isTileSolid(
  tile: TileType,
  col: number,
  row: number,
  act: ActId,
  rebuiltCairns: string[]
): boolean {
  if (tile === 'mist') {
    // Check if any rebuilt cairn in this act clears this mist tile
    for (const entity of WORLD_ENTITIES) {
      if (
        entity.act === act &&
        entity.kind === 'cairn' &&
        rebuiltCairns.includes(entity.id) &&
        entity.cairnMistTiles?.some((t) => t.x === col && t.y === row)
      ) {
        return false;
      }
    }
    return true;
  }

  return (
    tile === 'tree' ||
    tile === 'rock' ||
    tile === 'cliff' ||
    tile === 'chasm' ||
    tile === 'cabin'
  );
}

